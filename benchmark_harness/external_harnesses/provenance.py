"""Integrity helpers for externally synchronized source trees."""

from __future__ import annotations

import hashlib
import json
import os
import subprocess
from collections.abc import Sequence
from pathlib import Path
from typing import Any


class ExternalHarnessIntegrityError(RuntimeError):
    """Raised when an external source is not the pinned, contained checkout."""


def sha256_file(path: str | Path) -> str:
    digest = hashlib.sha256()
    try:
        with Path(path).open("rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
    except OSError as exc:
        raise ExternalHarnessIntegrityError(f"unable to hash external file: {path}") from exc
    return digest.hexdigest()


def run_git(args: Sequence[str], *, cwd: str | Path, timeout_seconds: float = 120.0) -> str:
    try:
        completed = subprocess.run(
            ["git", *args],
            cwd=Path(cwd),
            check=True,
            capture_output=True,
            text=True,
            timeout=timeout_seconds,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        raise ExternalHarnessIntegrityError(f"git command failed: git {' '.join(args)}") from exc
    return completed.stdout.strip()


def ensure_contained_tree(root: str | Path) -> None:
    """Reject symlinks that could make the child read outside its checkout."""

    base = Path(root).resolve()
    if not base.is_dir():
        raise ExternalHarnessIntegrityError(f"external source directory is missing: {base}")
    for directory, dirnames, filenames in os.walk(base, followlinks=False):
        # The isolated runtime is generated by ``uv sync`` and may contain
        # interpreter symlinks outside the source tree; it is not upstream
        # source and is verified separately by the manager.
        if ".venv" in dirnames:
            runtime_dir = Path(directory) / ".venv"
            if runtime_dir.is_symlink() and not runtime_dir.resolve().is_relative_to(base):
                raise ExternalHarnessIntegrityError(
                    f"external checkout symlink escapes source: {runtime_dir}"
                )
            dirnames.remove(".venv")
        for name in [*dirnames, *filenames]:
            path = Path(directory) / name
            if path.is_symlink() and not path.resolve().is_relative_to(base):
                raise ExternalHarnessIntegrityError(
                    f"external checkout symlink escapes source: {path}"
                )


def verify_git_checkout(
    source_dir: str | Path,
    *,
    repo_url: str | None = None,
    revision: str,
    tree_sha: str,
    uv_lock_sha256: str,
    pyproject_sha256: str,
) -> dict[str, Any]:
    """Verify revision, clean state, tree identity, and lock/project bytes."""

    source = Path(source_dir).resolve()
    ensure_contained_tree(source)
    if repo_url is not None:
        origin = run_git(["remote", "get-url", "origin"], cwd=source)
        if origin.rstrip("/") != repo_url.rstrip("/"):
            raise ExternalHarnessIntegrityError(
                f"external origin {origin!r} != pinned repository {repo_url!r}"
            )
    head = run_git(["rev-parse", "HEAD"], cwd=source)
    if head != revision:
        raise ExternalHarnessIntegrityError(f"external HEAD {head} != pinned revision {revision}")
    actual_tree = run_git(["rev-parse", "HEAD^{tree}"], cwd=source)
    if actual_tree != tree_sha:
        raise ExternalHarnessIntegrityError(
            f"external tree {actual_tree} != pinned tree {tree_sha}"
        )
    status = run_git(["status", "--porcelain"], cwd=source)
    # The isolated interpreter is runtime state, not upstream source.  It is
    # intentionally excluded from the clean-tree gate so verify() remains
    # usable even when a checkout was prepared by an older sync.
    dirty_source = [
        line
        for line in status.splitlines()
        if not (len(line) > 3 and line[3:].startswith(".venv/"))
    ]
    if dirty_source:
        raise ExternalHarnessIntegrityError("external checkout has uncommitted changes")
    lock_path = source / "uv.lock"
    project_path = source / "pyproject.toml"
    actual_lock = sha256_file(lock_path)
    actual_project = sha256_file(project_path)
    if actual_lock != uv_lock_sha256:
        raise ExternalHarnessIntegrityError("external uv.lock hash does not match the pin")
    if actual_project != pyproject_sha256:
        raise ExternalHarnessIntegrityError("external pyproject.toml hash does not match the pin")
    return {
        "head": head,
        "origin": origin if repo_url is not None else None,
        "tree_sha": actual_tree,
        "uv_lock_sha256": actual_lock,
        "pyproject_sha256": actual_project,
        "clean": True,
    }


def write_manifest(path: str | Path, manifest: dict[str, Any]) -> None:
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(f".{destination.name}.{os.getpid()}.tmp")
    temporary.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    os.replace(temporary, destination)


def read_manifest(path: str | Path) -> dict[str, Any]:
    try:
        value = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ExternalHarnessIntegrityError(f"external manifest is unreadable: {path}") from exc
    if not isinstance(value, dict):
        raise ExternalHarnessIntegrityError("external manifest must be a JSON object")
    return value


